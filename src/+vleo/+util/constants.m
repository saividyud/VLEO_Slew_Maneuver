function c = constants()
    persistent cachedConstants

    if isempty(cachedConstants)
        flatteningEarth = 1 / 298.257223563;
        cachedConstants = struct( ...
            'mu_earth', 3.986004418e14, ...
            'R_earth', 6378137.0, ...
            'J2_earth', 1.08263e-3, ...
            'omega_earth', 7.2921159e-5, ...
            'flattening_earth', flatteningEarth, ...
            'eccentricity_squared_earth', flatteningEarth * (2 - flatteningEarth), ...
            'gravity_zonal_coeffs', [1082e-6, -2.53e-6, 0]);
    end

    c = cachedConstants;
end
